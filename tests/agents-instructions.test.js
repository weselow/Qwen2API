const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { PER_FILE_SUM } = require('../tools/test-gate.js')

// AGENTS.md is read by agents and parsed by nothing, so its drift from the code
// and from the owner's decisions is checked here.

// Whatever line endings the checkout has.
const agents = fs.readFileSync(path.join(__dirname, '..', 'AGENTS.md'), 'utf8').replace(/\r\n/g, '\n')
const END = '<!-- END BEADS INTEGRATION -->'

// The file in three: what bd wrote above its block, the block itself, and what
// stands below it — where nothing generated goes.
const parts = () => {
  const begin = agents.search(/<!-- BEGIN BEADS INTEGRATION[^\n]*-->/)
  const end = agents.indexOf(END)
  assert.ok(begin >= 0 && end > begin, 'AGENTS.md must carry the beads block between its BEGIN and END markers')
  return { above: agents.slice(0, begin), block: agents.slice(begin, end), below: agents.slice(end + END.length) }
}

// Qwen2API-288, Qwen2API-vbc (1): the baseline's note and two comments in the
// gate point at a section "The test gate" that was not in the file.
test('AGENTS.md has the section "The test gate" that the baseline note and the gate point to, carrying the gate\'s own per-file sum', () => {
  assert.match(agents, /^## The test gate$/m)
  // Word for word: the hand cross-check and the gate cannot drift apart.
  assert.ok(agents.includes(`\n${PER_FILE_SUM}\n`), 'AGENTS.md ("The test gate") must carry the gate\'s PER_FILE_SUM verbatim')
  assert.match(agents, /^## Session Close: Leave Nothing Unsaved$/m)
})

// Qwen2API-ei4 — the owner's decisions of 2026-11-25. The block is generated by
// bd, and a regenerated one brings its original wording back: that is caught
// here, not by the next agent to read the file.
test('AGENTS.md: nothing above or inside the beads block tells the agent to push beads data to a remote', () => {
  const { above, block } = parts()
  // `bd dolt push` has failed since 2026-06-19; the local database is the only current one.
  for (const [where, text] of [['the top of the file', above], ['the beads block', block]]) {
    assert.doesNotMatch(text, /dolt push/, `${where} must not hold "dolt push": a regenerated block brings the step back unnoticed`)
  }
})

test('AGENTS.md: the block no longer bans MEMORY.md, and the two exceptions stand below it, where a regeneration does not reach', () => {
  const { block, below } = parts()
  assert.doesNotMatch(block, /do NOT use MEMORY\.md/)
  assert.match(below, /^## This project — two exceptions to the block above$/m)
  assert.match(below, /Never run `bd dolt push` here/)
  assert.match(below, /Keep both kinds of memory/)
  // Seen on a copy (2026-11-27): `bd init --reinit-local` appends a second generated block
  // at the end of the file, with the ban in other words. The block opens on a line of its
  // own; a mention inside a sentence is this repository talking about it.
  assert.doesNotMatch(below, /^<!-- BEGIN BEADS CODEX SETUP/m,
    'a second generated block was appended below the beads block: the owner\'s rule 2 is contradicted again')
  assert.doesNotMatch(below, /do not create ad hoc memory files/i,
    'the MEMORY.md ban in other words: the owner\'s rule 2 is contradicted again')
})

test('AGENTS.md: "Session Close" adds to steps 1 and 7 of the completion protocol by name, and both steps are still named so', () => {
  const { block, below } = parts()
  assert.match(block, /1\. \*\*File issues for remaining work\*\*/)
  assert.match(block, /7\. \*\*Hand off\*\*/)
  assert.match(below, /Adds to step 1 \("File issues for remaining work"\) and step 7 \("Hand off"\)/)
})
